#!/usr/bin/env python3
"""Export the three original authored road strips and forests, without generation.

Generated data is licensed original content and must remain ignored by Git.
Coordinates match the native browser models: Unity X reflected, +Y up, meters.
"""
import argparse
import hashlib
import json
import math
from collections import Counter
from pathlib import Path

import numpy as np
import UnityPy
from UnityPy.helpers.MeshHelper import MeshHandler

from export_web_assets import Exporter, ROOT, TREES, REFLECT, local_matrix, vec


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_scene(runtime, number):
    # Reuse the existing transform/asset readers, selecting the original scene.
    e = Exporter.__new__(Exporter)
    e.runtime = runtime
    files = [runtime / ('level' + str(number)), runtime / ('sharedassets' + str(number) + '.assets'),
        runtime / 'sharedassets1.assets', runtime / 'sharedassets0.assets', runtime / 'resources.assets']
    e.environment = UnityPy.load(*dict.fromkeys(str(p) for p in files))
    e.scene = next(f for f in e.environment.files.values() if getattr(f, 'name', '') == 'level' + str(number))
    e.gos = {o.path_id: o.read() for o in e.scene.objects.values() if o.type.name == 'GameObject'}
    e.transforms, e.components, e.world_cache = {}, {}, {}
    for go_id, go in e.gos.items():
        components = e.components[go_id] = {}
        for c in go.m_Component:
            kind = c.component.type.name
            if kind not in ['Transform', 'MeshFilter', 'MeshRenderer', 'CapsuleCollider', 'BoxCollider']:
                continue
            d = c.component.read()
            components[kind] = d
            if kind == 'Transform': e.transforms[c.component.m_PathID] = d
    return e


def reflected_world(e, go):
    return REFLECT @ e.world(e.go_transform(go)) @ REFLECT


def quaternion(matrix):
    # Stable matrix-to-quaternion conversion; scale is deliberately stripped.
    m = matrix[:3, :3].copy()
    m /= np.linalg.norm(m, axis=0)
    tr = np.trace(m)
    if tr > 0:
        s = math.sqrt(tr + 1) * 2
        q = [(m[2, 1] - m[1, 2]) / s, (m[0, 2] - m[2, 0]) / s,
            (m[1, 0] - m[0, 1]) / s, s / 4]
    else:
        i = int(np.argmax(np.diag(m)))
        j, k = (i + 1) % 3, (i + 2) % 3
        s = math.sqrt(1 + m[i, i] - m[j, j] - m[k, k]) * 2
        q = [0., 0., 0., (m[k, j] - m[j, k]) / s]
        q[i] = s / 4; q[j] = (m[j, i] + m[i, j]) / s; q[k] = (m[k, i] + m[i, k]) / s
    return np.asarray(q).tolist()


def pose(e, name):
    go = next(g for g in e.gos.values() if g.m_Name == name)
    m = reflected_world(e, go)
    forward = m[:3, 2] / np.linalg.norm(m[:3, 2])
    return {'position': m[:3, 3].tolist(), 'rotation': quaternion(m), 'forward': forward.tolist(),
        'matrix': m.T.reshape(-1).tolist(), 'sourcePathId': go.object_reader.path_id}


def rounded(value):
    if isinstance(value, float):
        return round(value, 6)
    if isinstance(value, dict): return {k: rounded(v) for k, v in value.items()}
    if isinstance(value, list): return [rounded(v) for v in value]
    return value


def validate_course(course):
    mesh = course['roadMesh']
    p = np.asarray(mesh['positions']).reshape(-1, 3)
    normals = np.asarray(mesh['normals']).reshape(-1, 3)
    indices = np.asarray(mesh['indices'], dtype=int).reshape(-1, 3)
    points = np.asarray(course['points'])
    expected = (p[::2] + p[1::2]) * .5
    if course['source']['stripReversedToMatchSpawn']: expected = expected[::-1]
    if course['source']['closedLoop']:
        expected = np.roll(expected[:-1], -course['source']['originalStartIndex'], axis=0)
        expected = np.concatenate([expected, expected[:1]])
    error = float(np.max(np.abs(expected - points)))
    finite = all(np.isfinite(np.asarray(mesh[k])).all() for k in ['positions', 'normals', 'uvs'])
    if not finite or not np.isfinite(points).all() or indices.min() < 0 or indices.max() >= len(p) or error > 1.1e-6:
        raise ValueError('Native course geometry validation failed.')
    for tree in course['trees']:
        if not all(math.isfinite(tree[k]) for k in ['x', 'y', 'z', 'yaw', 'scale', 'radius']) or tree['scale'] <= 0 or tree['radius'] <= 0:
            raise ValueError('Native forest transform validation failed.')
    a, b, c = p[indices[:, 0]], p[indices[:, 1]], p[indices[:, 2]]
    dot = (np.cross(b - a, c - a) * normals[indices[:, 0]]).sum(axis=1)
    return {'vertices': len(p), 'triangles': len(indices), 'finiteNumbersAndValidIndices': True,
        'maximumCenterlineVsStripError': error, 'sourceStripTrianglesOpposingSmoothedNormals': int((dot < -1e-9).sum()),
        'note': 'The small native strip orientation anomalies are retained, not repaired or generated by export.'}


def export_course(e, number, bases):
    road = next(g for g in e.gos.values() if g.m_Name == 'road_0001' and 'MeshFilter' in e.components[g.object_reader.path_id])
    pointer = e.components[road.object_reader.path_id]['MeshFilter'].m_Mesh
    mesh = pointer.read(); handler = MeshHandler(mesh); handler.process()
    vertices = np.asarray(handler.m_Vertices, dtype=float)[:, :3]
    if len(vertices) < 4 or len(vertices) % 2:
        raise ValueError('Original road does not contain a paired strip.')
    # This is the source EasyRoadsCenterline.TryBuild pairing, not a fitted path.
    transform = e.world(e.go_transform(road))
    world = (transform @ np.column_stack([vertices, np.ones(len(vertices))]).T).T[:, :3]
    world[:, 0] *= -1
    road_vertices = world.copy()
    left, right = world[::2], world[1::2]
    points = (left + right) * .5
    widths = np.linalg.norm(right - left, axis=1)
    start, finish = pose(e, 'StageStart'), pose(e, 'FinishTrigger')
    start_index = int(np.argmin(np.linalg.norm(points - np.array(start['position']), axis=1)))
    finish_index = int(np.argmin(np.linalg.norm(points - np.array(finish['position']), axis=1)))
    # Native spawn forward determines ordering if an authored mesh is reversed.
    before, after = points[max(0, start_index - 1)], points[min(len(points) - 1, start_index + 1)]
    dot = float(np.dot(after - before, start['forward']))
    reversed_strip = dot < 0
    if reversed_strip:
        points, widths, left, right = points[::-1], widths[::-1], right[::-1], left[::-1]
        start_index, finish_index = len(points) - 1 - start_index, len(points) - 1 - finish_index
    original_start_index, original_finish_index = start_index, finish_index
    closed_loop = float(np.linalg.norm(points[0] - points[-1])) < .01
    if closed_loop:
        # Native stage 1 is a circuit: its finish is just behind its start.
        # Rotate the identical authored samples so one lap runs start -> finish.
        # Keep the closing sample, without fitting or inventing any road points.
        count = len(points) - 1
        origin = start_index % count
        points, widths, left, right = [np.concatenate([np.roll(a[:-1], -origin, axis=0),
            np.roll(a[:-1], -origin, axis=0)[:1]], axis=0) for a in (points, widths, left, right)]
        start_index, finish_index = 0, (finish_index - origin) % count
    if finish_index <= start_index:
        raise ValueError(f'Course {number}: finish precedes spawn after native direction alignment.')
    distances = np.r_[0., np.cumsum(np.linalg.norm(np.diff(points, axis=0), axis=1))]
    trees, variants, matrix_fallbacks = [], Counter(), 0
    max_error = 0.
    for go_id, components in e.components.items():
        collider = components.get('CapsuleCollider')
        if collider is None or not collider.m_Enabled or collider.m_IsTrigger: continue
        go = e.gos[go_id]
        name = go.m_Name.split(' (')[0]
        if name not in TREES or not go.m_IsActive: continue
        variant = TREES.index(name); world = reflected_world(e, go)
        placement = world @ np.linalg.inv(bases[name])
        scale = float(np.linalg.norm(placement[:3, 0]))
        yaw = float(math.atan2(placement[0, 2], placement[2, 2]))
        simple = np.array([[math.cos(yaw), 0, math.sin(yaw)], [0, 1, 0], [-math.sin(yaw), 0, math.cos(yaw)]]) * scale
        error = float(np.max(np.abs(simple - placement[:3, :3])))
        max_error = max(max_error, error)
        center = np.array(vec(collider.m_Center) + [1.]); center[0] *= -1
        center = world @ center
        source_scale = np.linalg.norm(world[:3, :3], axis=0)
        axis = collider.m_Direction
        radius = float(collider.m_Radius * max(source_scale[(axis + 1) % 3], source_scale[(axis + 2) % 3]))
        entry = {'x': float(center[0]), 'y': float(world[1, 3]), 'z': float(center[2]),
            'yaw': yaw, 'scale': scale, 'radius': radius, 'variant': variant, 'solid': True}
        if error > 1e-5:
            # A few authored trees may be tilted or nonuniformly scaled. The
            # matrix is exact placement before multiplying the existing model.
            entry['matrix'] = placement.T.reshape(-1).tolist(); matrix_fallbacks += 1
        trees.append(entry); variants[name] += 1
    mud = []
    for obj in e.scene.objects.values():
        if obj.type.name != 'MonoBehaviour': continue
        data = obj.read_typetree(check_read=False, wrap=True)
        try: kind = data.m_Script.read().m_ClassName
        except Exception: continue
        if kind != 'MudDepositTrigger': continue
        go = data.m_GameObject.read(); matrix = reflected_world(e, go)
        raw = obj.get_raw_data()
        import struct
        amount, cooldown = struct.unpack_from('<ff', raw, 32)
        point = matrix[:3, 3]
        index = int(np.argmin(np.linalg.norm(points - point, axis=1)))
        box = e.components[go.object_reader.path_id].get('BoxCollider')
        radius = float(np.max(np.array(vec(box.m_Size)) * np.linalg.norm(matrix[:3, :3], axis=0)) * .5) if box else 2.5
        mud.append({'x': float(point[0]), 'y': float(point[1]), 'z': float(point[2]), 'index': index,
            'amount': amount, 'cooldown': cooldown, 'radius': radius})
    level = e.runtime / ('level' + str(number))
    course = {'id': str(number), 'name': f'{number:02} / STAGE {number:02}', 'native': True,
        'profile': number + 5, 'source': {'scene': str(number), 'levelFile': level.name, 'sha256': digest(level),
            'roadObjectPathId': road.object_reader.path_id, 'roadMeshPathId': mesh.object_reader.path_id,
            'roadMeshFile': mesh.object_reader.assets_file.name, 'stripReversedToMatchSpawn': reversed_strip,
            'closedLoop': closed_loop, 'originalStartIndex': original_start_index, 'originalFinishIndex': original_finish_index},
        'points': points.tolist(), 'width': float(np.median(widths)), 'widths': widths.tolist(),
        'distances': distances.tolist(), 'length': float(distances[-1]), 'startIndex': start_index,
        'finishIndex': finish_index, 'startPose': start, 'finishPose': finish,
        'trees': trees, 'mud': mud, 'gates': {'start': pose(e, 'StageStart'), 'finish': pose(e, 'StageFinish')}}
    triangles = np.concatenate([np.asarray(t, dtype=np.uint32)[:, [0, 2, 1]].reshape(-1)
        for t in handler.get_triangles()])
    normal = np.asarray(handler.m_Normals, dtype=float)[:, :3]
    normal = (np.linalg.inv(transform[:3, :3]).T @ normal.T).T
    normal[:, 0] *= -1
    normal /= np.maximum(1e-12, np.linalg.norm(normal, axis=1)[:, None])
    uv = np.asarray(handler.m_UV0, dtype=float)[:, :2]; uv[:, 1] = 1 - uv[:, 1]
    course['roadMesh'] = {'positions': road_vertices.reshape(-1).tolist(), 'normals': normal.reshape(-1).tolist(),
        'uvs': uv.reshape(-1).tolist(), 'indices': triangles.tolist(),
        'coordinateSystem': 'World glTF basis; X reflected, winding reversed, UV V flipped',
        'material': 'Native road material / dirtRoad_A', 'vertexCount': len(road_vertices)}
    course = rounded(course)
    report = {'id': str(number), 'pointCount': len(points), 'treeCount': len(trees), 'treeVariants': dict(variants),
        'widthMin': float(widths.min()), 'widthMax': float(widths.max()), 'startIndex': start_index,
        'finishIndex': finish_index, 'length': float(distances[-1]), 'matrixFallbacks': matrix_fallbacks,
        'maximumYawScaleMatrixError': max_error, 'mudTriggerCount': len(mud), 'validation': validate_course(course)}
    return course, rounded(report)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--runtime', type=Path, default=ROOT / 'local/builds/RightRightRight-0.3.0-alpha.5/player/GameRuntime_Data')
    parser.add_argument('--output', type=Path, default=ROOT / 'web/shared/native-courses.generated.json')
    parser.add_argument('--report', type=Path, default=ROOT / 'local/web-assets/native-courses-provenance.json')
    args = parser.parse_args()
    first = load_scene(args.runtime, 1)
    bases = {}
    for name in TREES:
        go = next(g for g in first.gos.values() if g.m_Name == name and 'CapsuleCollider' in first.components[g.object_reader.path_id])
        m = REFLECT @ local_matrix(first.go_transform(go)) @ REFLECT; m[:3, 3] = 0
        bases[name] = m
    courses, reports = [], []
    for number in (1, 2, 3):
        e = first if number == 1 else load_scene(args.runtime, number)
        course, report = export_course(e, number, bases)
        courses.append(course); reports.append(report)
        print(json.dumps(report), flush=True)
    document = {'schemaVersion': 1, 'coordinateSystem': 'Unity X reflected; +Y up; +Z forward; meters',
        'copyright': 'Original courses and assets: Stellux Interactive. Used under developer permission stated by the project owner; excluded from the source-code MIT license.',
        'treeVariants': TREES, 'courses': courses}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    temporary = args.output.with_name(args.output.name + '.tmp')
    temporary.write_text(json.dumps(document, separators=(',', ':'), allow_nan=False) + '\n')
    temporary.replace(args.output)
    report = {'outputSha256': digest(args.output), 'bytes': args.output.stat().st_size, 'courses': reports,
        'sourceFiles': {name: digest(args.runtime / name) for name in ['level1', 'level2', 'level3',
            'sharedassets1.assets', 'sharedassets2.assets', 'sharedassets3.assets']},
        'notes': ['Road positions are exact native mesh strip-pair averages; six decimal place storage precision.',
            'Forest placements are serialized scene instances, with native trunk collider centers/radii.',
            'No procedural road replacement or extra forest has been generated.',
            'Runtime-generated decorators/terrain and full native car handling are outside this export.']}
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + '\n')
    print('NATIVE_COURSES_READY ' + str(args.output) + ' ' + str(args.output.stat().st_size), flush=True)


if __name__ == '__main__': main()
